#!/usr/bin/env bash
#
# The starship prompt (opt-in; see starship/ask.sh). The starship binary comes from
# mise: script/lib/common.sh adds it to the tools mise/install.sh installs when
# STARSHIP=1. This script does the rest:
#
#   - writes ~/.config/dotfiles/starship.zsh, which zsh/zshrc.symlink sources after
#     oh-my-zsh, so starship's prompt replaces the oh-my-zsh theme
#   - copies starship/starship.toml.example to ~/.config/starship.toml, only if that
#     file does not exist (an existing file, or a symlink into a stow repo, is never touched)
#
# Declining removes the generated starship.zsh and nothing else: your starship.toml stays.
# Safe to re-run. Reads the answers saved by script/ask.

set -euo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/script/lib/common.sh"
install_prelude

INIT_FILE="$CONFIG_DIR/starship.zsh"
CONFIG_SRC="$DOTFILES_ROOT/starship/starship.toml.example"
CONFIG_DST="${XDG_CONFIG_HOME:-$HOME/.config}/starship.toml"

if [[ "${STARSHIP:-0}" != 1 ]]; then
  # Only remove what we generated, so choosing "no" later turns the prompt back off.
  [[ ! -f "$INIT_FILE" ]] || { rm -f "$INIT_FILE"; say "starship turned off (removed $INIT_FILE)."; }
  exit 0
fi

if ! mise which starship >/dev/null 2>&1; then
  warn "starship is not installed by mise yet. Run: mise use -g starship   then run starship/install.sh again."
  exit 0
fi

mkdir -p "$CONFIG_DIR"
cat > "$INIT_FILE" <<'EOF'
# Generated by starship/install.sh; run script/ask with RECONFIGURE=1 to change.
# Sourced by ~/.zshrc after oh-my-zsh, so this prompt replaces the oh-my-zsh theme.
if command -v starship >/dev/null 2>&1; then
  eval "$(starship init zsh)"
fi
EOF
say "Writing $INIT_FILE"

if [[ -e "$CONFIG_DST" || -L "$CONFIG_DST" ]]; then
  say "${CONFIG_DST/#$HOME/~} already exists; leaving it."
else
  mkdir -p "$(dirname "$CONFIG_DST")"
  cp "$CONFIG_SRC" "$CONFIG_DST"
  say "Created ${CONFIG_DST/#$HOME/~} from starship/starship.toml.example. Edit it to taste (https://starship.rs/config/)."
fi
say "Open a new terminal to see the starship prompt."
